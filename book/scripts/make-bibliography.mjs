// Generate bibliography.md listing every entry in references.bib.
// mystmd has no "cite all" directive, so this page cites each key inside a
// hidden block; mystmd then renders the full reference list at the bottom.
// Usage (from book/): node scripts/make-bibliography.mjs

import { readFileSync, writeFileSync } from "node:fs";

const bib = readFileSync("references.bib", "utf8");

// Sort by first author (braces stripped), then year, since mystmd lists
// references in order of first citation.
const keys = bib
  .split(/^(?=\s*@)/m)
  .map((text) => {
    const head = text.match(/^\s*@(\w+)\s*\{\s*([^,\s]+)\s*,/);
    if (!head || ["comment", "string", "preamble"].includes(head[1].toLowerCase())) return null;
    const author = (text.match(/\bauthor\s*=\s*(\{[^\n]*)/i)?.[1] ?? "")
      .replace(/[{}]/g, "")
      .trim()
      .replace(/^the\s+/i, "");
    const year = text.match(/\byear\s*=\s*\{?(\d{4})/i)?.[1] ?? "";
    return { key: head[2], sortkey: `${author.split(/,| and /)[0].toLowerCase()} ${year}` };
  })
  .filter(Boolean)
  .sort((a, b) => a.sortkey.localeCompare(b.sortkey))
  .map((e) => e.key);

const page = `---
title: Bibliography
---

<!-- GENERATED by scripts/make-bibliography.mjs from references.bib -- do not edit. -->

All works referenced in this book.

:::{div}
:class: hidden
${keys.map((k) => `[@${k}]`).join("\n")}
:::
`;

writeFileSync("bibliography.md", page);
console.log(`bibliography.md: ${keys.length} entries`);
